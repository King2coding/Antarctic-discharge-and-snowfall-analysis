def _month_start(value):
    """Return a timestamp normalized to the first day of its calendar month."""
    return pd.Timestamp(value).to_period("M").to_timestamp()


def _latest_matching_file(pattern):
    """Return the newest lexicographically dated file matching ``pattern``."""
    matches = sorted(glob.glob(pattern))
    if not matches:
        raise FileNotFoundError(f"No files match: {pattern}")
    return matches[-1]


def choose_airs_worker_count(max_workers, reserved_cores=8):
    """Choose a conservative worker count from the current server load.

    Linux load average is not a perfect measure of free CPU, but it provides a
    useful guardrail on a shared server.  The calculation never exceeds the
    user-configured maximum and always leaves ``reserved_cores`` unclaimed.
    """
    logical_cores = os.cpu_count() or 1
    try:
        one_minute_load = float(os.getloadavg()[0])
    except (AttributeError, OSError):
        one_minute_load = 0.0

    estimated_free = logical_cores - int(np.ceil(one_minute_load))
    available_after_reserve = estimated_free - int(reserved_cores)
    selected = max(1, min(int(max_workers), available_after_reserve))

    print(
        "AIRS worker selection: "
        f"logical_cores={logical_cores}, "
        f"one_minute_load={one_minute_load:.1f}, "
        f"reserved_cores={reserved_cores}, workers={selected}"
    )
    return selected


def load_gpcp_monthly(start_date, end_date, gpcp_dir=None):
    """Load GPCP V3.3 and convert monthly mean mm/day to mm/month.

    Filename dates are used as the authoritative chronology, matching the
    established project driver and avoiding previously observed time-coordinate
    duplication in ``open_mfdataset``.
    """
    # Resolve the configured archive at call time. This avoids retaining an old
    # path when Section 2 is rerun in an already-active interactive kernel.
    if gpcp_dir is None:
        gpcp_dir = GPCP_DIR

    start_month = _month_start(start_date)
    end_month = _month_start(end_date)
    selected = []
    selected_times = []

    for file_path in sorted(glob.glob(os.path.join(gpcp_dir, "*.nc4"))):
        match = re.search(r"GPCPMON_L3_(\d{6})_V3\.3\.nc4$", file_path)
        if match is None:
            continue
        timestamp = pd.to_datetime(match.group(1), format="%Y%m")
        if start_month <= timestamp <= end_month:
            selected.append(file_path)
            selected_times.append(timestamp)

    # A missing source month would silently distort climatologies and metrics,
    # so require an uninterrupted monthly record before continuing.
    expected = pd.date_range(start_month, end_month, freq="MS")
    if pd.DatetimeIndex(selected_times).tolist() != expected.tolist():
        missing = expected.difference(pd.DatetimeIndex(selected_times))
        raise ValueError(f"GPCP monthly archive is incomplete: {missing.tolist()}")

    # ``combine='nested'`` preserves the explicitly sorted filename order.
    # The timestamp derived above is then assigned back to each monthly slice.
    dataset = xr.open_mfdataset(
        selected,
        combine="nested",
        concat_dim="time",
        coords="minimal",
        compat="override",
        parallel=True,
        engine="netcdf4",
        chunks={"time": 120, "lat": 180, "lon": 360},
        cache=False,
    ).assign_coords(time=pd.DatetimeIndex(selected_times))

    dataset = ds_swaplon(dataset)
    precipitation = dataset["sat_gauge_precip"].copy()
    # GPCP stores a monthly mean precipitation rate in mm/day.  Multiplying by
    # the number of calendar days gives the monthly accumulation in mm/month.
    days = xr.DataArray(
        precipitation.time.dt.days_in_month,
        dims=["time"],
        coords={"time": precipitation.time},
    )
    precipitation = (precipitation * days).where(np.isfinite(precipitation))
    precipitation = precipitation.sel(lat=slice(-60, -90))
    precipitation.name = "gpcp_mm_month"
    precipitation.attrs["units"] = "mm/month"
    return precipitation


def load_era5_monthly(start_date, end_date, era5_file=ERA5_FILE):
    """Load the established ERA5 monthly file and convert it to mm/month."""
    dataset = xr.open_dataset(era5_file, engine="netcdf4")[["tp"]]
    dataset = replace_fill_with_nan(ds_swaplon(dataset))
    if "valid_time" in dataset.dims or "valid_time" in dataset.coords:
        dataset = dataset.rename({"valid_time": "time"})
    dataset = dataset.sortby("longitude").sortby("latitude", ascending=False)
    dataset = dataset.drop_vars(["expver", "number"], errors="ignore")
    # Normalize timestamps to month starts so exact merges with GPCP and AIRS
    # do not fail because products use different within-month timestamps.
    dataset = dataset.assign_coords(
        time=pd.to_datetime(dataset.time.values).to_period("M").to_timestamp()
    )
    dataset = dataset.sel(time=slice(start_date, end_date))
    # This established project file stores ERA5 ``tp`` as a monthly mean daily
    # rate in metres/day: metres -> millimetres, then rate -> monthly total.
    days = xr.DataArray(
        dataset.time.dt.days_in_month,
        dims=["time"],
        coords={"time": dataset.time},
    )
    precipitation = dataset["tp"] * 1000.0 * days
    precipitation = precipitation.sel(latitude=slice(-60, -90))
    precipitation = precipitation.rename({"latitude": "lat", "longitude": "lon"})
    precipitation.name = "era5_mm_month"
    precipitation.attrs["units"] = "mm/month"
    return precipitation


def load_airs_monthly_with_completeness(
    start_date,
    end_date,
    daily_dir=AIRS_DAILY_DIR,
    min_completeness=AIRS_MIN_MONTHLY_COMPLETENESS,
    num_workers=1,
):
    """Aggregate AIRS daily mm/day files to quality-controlled monthly totals.

    Months meeting ``min_completeness`` are summed and multiplied by
    expected_days / available_days to account for a small number of missing
    whole-day files.  Months below the threshold are represented by an all-NaN
    field.  The returned QA table records the decision for every month.
    """
    start_month = _month_start(start_date)
    end_month = _month_start(end_date)
    expected_months = pd.date_range(start_month, end_month, freq="MS")

    # Build a complete month inventory first.  This makes missing whole files
    # visible instead of allowing xarray to aggregate an incomplete month as if
    # it represented the full calendar month.
    files_by_month = {month: [] for month in expected_months}
    for file_path in sorted(glob.glob(os.path.join(daily_dir, "*.nc"))):
        match = re.search(r"\.(\d{8})\.nc$", file_path)
        if match is None:
            continue
        day = pd.to_datetime(match.group(1), format="%Y%m%d")
        month = day.to_period("M").to_timestamp()
        if month in files_by_month:
            files_by_month[month].append(file_path)

    first_available = next(
        (files[0] for files in files_by_month.values() if files),
        None,
    )
    if first_available is None:
        raise FileNotFoundError("No AIRS daily files found for requested period.")

    # A spatial template is needed for rejected months.  Filling it with NaN
    # preserves the complete monthly time axis and produces a visible gap in
    # plots without inventing an AIRS estimate.
    with xr.open_dataset(first_available, cache=False) as template_ds:
        # Only the Antarctic portion of one daily field is used as the spatial
        # template.  Copy coordinates and dimensions before closing the file.
        template = (
            template_ds["precipitation"]
            .isel(time=0, drop=True)
            .sel(lat=slice(-60, -90))
            .load()
        )
        template_dims = template.dims
        template_coords = {
            dim: template.coords[dim].values.copy()
            for dim in template_dims
        }
        template_shape = template.shape

    if int(num_workers) < 1:
        raise ValueError("num_workers must be at least 1.")

    monthly_fields = []
    qa_rows = []

    # Reuse one process pool for the entire decade rather than repeatedly
    # starting workers for every month.  The serial fallback uses Python's map
    # directly and is useful when server traffic is high or for debugging.
    executor = None
    if int(num_workers) > 1:
        executor = concurrent.futures.ProcessPoolExecutor(
            max_workers=int(num_workers)
        )

    try:
        for month in expected_months:
            files = files_by_month[month]
            expected_days = calendar.monthrange(month.year, month.month)[1]
            available_days = len(files)
            completeness = available_days / expected_days
            accepted = completeness >= min_completeness

            if accepted:
                # IMPORTANT MEMORY-SAFETY DESIGN
                # ------------------------------
                # Do not use open_mfdataset() for the daily AIRS files here.
                # Its parallel task graph can open many full global files at
                # once and caused the interactive kernel to be terminated by
                # the operating system.  Instead, read one Antarctic daily
                # slice at a time, accumulate it into fixed-size NumPy arrays,
                # and close the source file immediately.  Peak memory therefore
                # does not grow with the number of days or months processed.
                monthly_sum = np.zeros(template_shape, dtype=np.float64)
                monthly_valid_count = np.zeros(template_shape, dtype=np.int16)

                if executor is None:
                    daily_results = map(
                        read_airs_daily_antarctic_field,
                        files,
                    )
                else:
                    # chunksize=1 keeps dispatch granular and bounds how many
                    # returned spatial arrays can wait in the parent process.
                    daily_results = executor.map(
                        read_airs_daily_antarctic_field,
                        files,
                        chunksize=1,
                    )

                for daily_values in daily_results:
                    # Preserve grid-cell missing values: a cell receives a
                    # monthly value only if at least one valid daily estimate
                    # was present.
                    if daily_values.shape != template_shape:
                        raise ValueError(
                            f"Unexpected AIRS daily shape {daily_values.shape}; "
                            f"expected {template_shape}."
                        )
                    valid_cells = np.isfinite(daily_values)
                    monthly_sum[valid_cells] += daily_values[valid_cells]
                    monthly_valid_count[valid_cells] += 1

                    # Explicitly release each returned daily array before the
                    # next result is consumed by the parent kernel.
                    del daily_values, valid_cells

                monthly_values_valid = monthly_valid_count > 0
                monthly_values = np.full(template_shape, np.nan, dtype=np.float32)
                monthly_values[monthly_values_valid] = (
                    monthly_sum[monthly_values_valid]
                    * expected_days
                    / available_days
                ).astype(np.float32)

                monthly = xr.DataArray(
                    monthly_values,
                    dims=template_dims,
                    coords=template_coords,
                    name="precipitation",
                )
                status = (
                    "retained_and_scaled"
                    if available_days < expected_days
                    else "complete"
                )
            else:
                # Months below 90% completeness are too incomplete for
                # defensible scaling.  Retain their timestamps but replace the
                # field with NaN.
                monthly = xr.DataArray(
                    np.full(template_shape, np.nan, dtype=np.float32),
                    dims=template_dims,
                    coords=template_coords,
                    name="precipitation",
                )
                status = "excluded_as_nan"

            monthly = monthly.expand_dims(time=[month])
            monthly_fields.append(monthly)
            qa_rows.append({
                "time": month,
                "expected_days": expected_days,
                "available_days": available_days,
                "completeness_fraction": completeness,
                "accepted": accepted,
                "status": status,
                "scale_factor": expected_days / available_days if accepted else np.nan,
                "num_workers": int(num_workers),
            })

            # A compact progress message makes a long interactive cell
            # observable without printing one line for every daily file.
            print(
                f"AIRS {month:%Y-%m}: "
                f"{available_days:02d}/{expected_days:02d} days; {status}"
            )
    finally:
        if executor is not None:
            executor.shutdown(wait=True, cancel_futures=True)

    precipitation = xr.concat(monthly_fields, dim="time")
    precipitation.name = "airs_mm_month"
    precipitation.attrs.update({
        "units": "mm/month",
        "daily_source_units": "mm/day",
        "minimum_monthly_completeness": min_completeness,
        "missing_month_policy": "months below threshold assigned NaN",
    })
    return precipitation, pd.DataFrame(qa_rows)


def reproject_monthly_to_common_grid(data, target_template, basin_mask):
    """Reproject a monthly lat/lon field and apply the common AIS basin mask."""
    source = data.rio.set_spatial_dims(x_dim="lon", y_dim="lat", inplace=False)
    source = source.rio.write_crs("EPSG:4326", inplace=False)
    # Nearest-neighbour remapping matches the established project workflow and
    # avoids smoothing values while placing all products on identical cells.
    result = source.rio.reproject_match(
        target_template,
        resampling=Resampling.nearest,
    )
    rename_map = {}
    if "x" in result.dims:
        rename_map["x"] = "lon"
    if "y" in result.dims:
        rename_map["y"] = "lat"
    if rename_map:
        result = result.rename(rename_map)
    result = replace_fill_with_nan(result)
    result = result.sortby("lon").sortby("lat", ascending=False)
    return result.where(basin_mask.notnull()).where(result.lat < -60)


def derive_seasonal_transfer_factors_from_monthly_table(monthly_factor_table):
    """Convert operational monthly guide/GPCP ratios to seasonal ratios.

    This is not an unweighted average of the three monthly factors.  It uses
    the saved corrected-guide and de-adjusted-GPCP climatological means:

        seasonal CF = sum(corrected F17 monthly means)
                      / sum(de-adjusted GPCP monthly means)
    """
    month_to_season = {
        12: "DJF", 1: "DJF", 2: "DJF",
        3: "MAM", 4: "MAM", 5: "MAM",
        6: "JJA", 7: "JJA", 8: "JJA",
        9: "SON", 10: "SON", 11: "SON",
    }
    table = monthly_factor_table.copy()
    table["month"] = table["month"].astype(int)
    table["season"] = table["month"].map(month_to_season)
    required = {"corrected_guide_mean", "gpcp_mean", "month", "season"}
    missing = required.difference(table.columns)
    if missing:
        raise ValueError(f"Operational factor table lacks: {sorted(missing)}")

    # Summing numerator and denominator separately is essential.  A simple
    # arithmetic mean of three monthly ratios would give every month equal
    # weight regardless of its precipitation magnitude and would not equal the
    # ratio of seasonal totals.
    seasonal = (
        table.groupby("season", as_index=False)
        .agg(
            corrected_guide_mean=("corrected_guide_mean", "sum"),
            gpcp_mean=("gpcp_mean", "sum"),
        )
    )
    seasonal["transfer_factor"] = (
        seasonal["corrected_guide_mean"] / seasonal["gpcp_mean"]
    )
    order = {"DJF": 1, "MAM": 2, "JJA": 3, "SON": 4}
    return (
        seasonal.assign(season_order=seasonal.season.map(order))
        .sort_values("season_order")
        .drop(columns="season_order")
        .reset_index(drop=True)
    )


def apply_operational_factors_to_regional_gpcp(
    regional_df,
    monthly_factor_table,
    seasonal_factor_table,
):
    """Create monthly- and seasonal-CF corrected regional GPCP series."""
    original = regional_df[regional_df["product"] == GPCP_NAME].copy()
    original["time"] = pd.to_datetime(original["time"])
    original["month"] = original.time.dt.month
    original["season"] = np.select(
        [
            original.month.isin([12, 1, 2]),
            original.month.isin([3, 4, 5]),
            original.month.isin([6, 7, 8]),
            original.month.isin([9, 10, 11]),
        ],
        ["DJF", "MAM", "JJA", "SON"],
        default=None,
    )

    # Convert the factor tables into lookups keyed by calendar month/season.
    # The same values repeat every year; no historical data are used to refit
    # or update them.
    monthly_lookup = monthly_factor_table.set_index("month")["transfer_factor"]
    seasonal_lookup = seasonal_factor_table.set_index("season")["transfer_factor"]
    # Correction equation used for both methods:
    #   corrected GPCP = (published GPCP / 1.4) * operational factor
    de_adjusted = original["precipitation"] / GPCP_ANTARCTIC_LEGACY_FACTOR

    monthly_corrected = original.copy()
    monthly_corrected["precipitation"] = (
        de_adjusted * monthly_corrected.month.map(monthly_lookup)
    )
    monthly_corrected["product"] = GPCP_MONTHLY_CORR_NAME

    seasonal_corrected = original.copy()
    seasonal_corrected["precipitation"] = (
        de_adjusted * seasonal_corrected.season.map(seasonal_lookup)
    )
    seasonal_corrected["product"] = GPCP_SEASONAL_CORR_NAME

    keep = ["region", "product", "time", "precipitation"]
    return pd.concat(
        [regional_df[keep], monthly_corrected[keep], seasonal_corrected[keep]],
        ignore_index=True,
    )


def subset_period(dataframe, start_date, end_date):
    """Return an inclusive monthly slice from a tidy regional dataframe."""
    data = dataframe.copy()
    data["time"] = pd.to_datetime(data["time"])
    return data[data.time.between(_month_start(start_date), _month_start(end_date))].copy()


def plot_historical_monthly_timeseries(
    dataframe,
    product_order,
    title,
    region="Antarctica",
    year_tick_interval=1,
):
    """Plot a decade-long monthly series with a clean stakeholder-ready layout.

    The data remain monthly, but only one January tick per year is labelled.
    This retains chronological context without allowing x-axis text to compete
    with the lines or legend.
    """
    selected = dataframe[dataframe.region == region].copy()
    selected["time"] = pd.to_datetime(selected["time"])
    selected = selected.sort_values("time")

    fig, ax = plt.subplots(figsize=(15, 6.5), dpi=150)

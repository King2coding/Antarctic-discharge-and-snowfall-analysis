# =============================================================================
# SECTION 5. LOAD AND VALIDATE FINAL 2013-2020 OPERATIONAL FACTORS
# =============================================================================
# Required first: Sections 1-3.
# Produces: 12 monthly and 4 seasonal GPCP transfer factors.
# No factors are estimated from the 1992-2001 or 2003-2012 test periods.

final_monthly_cf_file = _latest_matching_file(FINAL_MONTHLY_CF_PATTERN)

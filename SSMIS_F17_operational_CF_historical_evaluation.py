"""Out-of-period evaluation of operational SSMIS-F17-guided GPCP factors.

This driver is intentionally separate from the 2013-2020 scenario-development
driver.  The final factors derived there are treated as fixed inputs here and
are applied unchanged to historical GPCP data.

Primary experiments
-------------------
1. AIRS-era independent comparison: 2003-2012 (AIRS, ERA5, and GPCP).
2. Pre-AIRS historical comparison: 1992-2001 (ERA5 and GPCP).

The script is arranged as VS Code/Jupyter ``#%%`` cells so that each numbered
section can be run interactively and inspected before proceeding.

Scientific interpretation
-------------------------
* SSMIS F17 is not required during the historical test periods.  It was used
  during 2013-2020 to derive the fixed operational-candidate factors.
* The historical tests ask how those fixed factors behave when transferred to
  periods that were not used to estimate them.
* AIRS and ERA5 are comparison products, not assumed truth over Antarctica.
  Results therefore describe agreement, consistency, and stability rather
  than proving that one corrected estimate is objectively more accurate.
* GPCP's existing Antarctic factor of 1.4 is removed before applying either
  new correction.  This avoids multiplying the new factors on top of the
  legacy adjustment.

Interactive section map
-----------------------
Sections 1-3 : imports, parameters, and reusable helper functions.
Section 4    : common 0.1-degree AIS grid and regional masks.
Section 5    : load the final 2013-2020 monthly factors and derive the
               corresponding seasonal factors.
Section 6    : load historical GPCP and ERA5 monthly fields.
Section 7    : aggregate daily AIRS files and create the completeness audit.
Section 8    : remap all products and calculate AIS/WAIS/EAIS means.
Section 9    : apply the fixed monthly and seasonal corrections.
Section 10   : make the first chronological comparison figures.
Section 11   : calculate paired monthly statistics.

Run the sections in numerical order after restarting the interactive kernel.
"""

